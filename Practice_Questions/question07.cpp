#include<iostream> 
using namespace std ; 
int main() { 
    int a ;
    int b ;
    cout<<"Enter first number : \n" ; 
    cin>>a ; 
    cout<<"Enter second number : \n" ; 
    cin>>b ; 
    cout<<"\n" ; 
    cout<<"Before swapping : \na = "<<a<<"\nb = "<<b ; 
    cout<<"\n" ; 
    cout<<"After swapping : \na = "<<b<<"\nb = "<<a ; 
    return 0 ; 
    
}